/* ============================================================
   PneumoScan AI — API Helper Functions
   File: static/js/api.js
   ============================================================
   All fetch() calls to the Flask backend live here.
   Endpoints used:
     POST /api/predict   → Run inference on uploaded X-ray
     GET  /api/stats     → Summary counts (total/normal/bacterial/viral)
     GET  /api/history   → All past scan records
     GET  /api/metadata  → Model metadata (accuracy, recall)
     DELETE /api/history/:id → Delete a single record
   ============================================================ */


/**
 * POST /api/predict
 * Sends X-ray image + patient info to the Flask backend.
 * Returns a record with prediction, confidence, heatmap images, etc.
 *
 * @param {File}   file         - The image file from the file input
 * @param {string} patientName  - Patient's name (defaults to 'Anonymous')
 * @param {string} patientId    - Patient ID (auto-generated by backend if blank)
 * @returns {Promise<Object>}   - Prediction record
 */
async function apiPredict(file, patientName, patientId) {
  const fd = new FormData();
  fd.append('file',         file);
  fd.append('patient_name', patientName || 'Anonymous');
  fd.append('patient_id',   patientId   || '');

  const res  = await fetch('/api/predict', { method: 'POST', body: fd });
  const data = await res.json();
  if (data.error) throw new Error(data.error);
  return data;
}


/**
 * GET /api/stats
 * Returns aggregate counts of all scans.
 *
 * @returns {Promise<Object>} - { total, normal, bacterial, viral, avg_confidence }
 */
async function apiStats() {
  const res = await fetch('/api/stats');
  return res.json();
}


/**
 * GET /api/history
 * Returns array of all past scan records, newest first.
 *
 * @returns {Promise<Array>} - Array of scan records
 */
async function apiHistory() {
  const res = await fetch('/api/history');
  return res.json();
}


/**
 * GET /api/metadata
 * Returns model metadata loaded from model_metadata.json.
 * Includes: class_names, img_size, test_accuracy, test_macro_recall,
 *           test_recall_per_class, model_arch, imagenet_mean/std
 *
 * @returns {Promise<Object>} - Model metadata object
 */
async function apiMetadata() {
  const res = await fetch('/api/metadata');
  return res.json();
}


/**
 * DELETE /api/history/:id
 * Deletes a single scan record by its UUID.
 *
 * @param {string} id - The UUID of the scan record to delete
 * @returns {Promise<Object>} - { success: true }
 */
async function apiDeleteRecord(id) {
  const res = await fetch('/api/history/' + id, { method: 'DELETE' });
  return res.json();
}
